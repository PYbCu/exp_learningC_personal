#include<stdio.h>
void main()
{
	int i, j, arr[8] = { 0 };
	printf("请输入8个整数：");
	for (i = 0;i < 8;i++)
	{
		scanf_s("%d", &arr[i]);
	}
	printf("\n所有出现超过一次的整数有：");
	for (i = 0;i < 8;i++)
	{
		int flag = 0;
		for (j = i-1; j >=0; j--)//j=i是错的，因为自己和自己比，怎么都是flag=1!
			//for的第二个式子是条件表达式，当其为真时，才能够继续步入循环
		{
			if (arr[i] == arr[j])//往前查，如果有了与之相同的数，那么做标记，该次循环往后查时，用continue以跳出该次循环，做往后查的工作
			{
				flag = 1;
				break;
			}
		}
		if (flag == 1)//逻辑是，只有当往前查时没有重复的数时，往后查到重复数才打印
			continue;//注：contiune是指跳出本轮循环，还在循环体中，跳过本次循环的剩余步骤，直接进行下一次的循环
		for (j = i+1;j < 8;j++)
		{
			if (arr[i] == arr[j])
			{
				printf("%d ", arr[i]);
				break;
			}
		}
	}
	printf("\n");
}
//eg.1 2 2：若没有往前查往后查的去重操作，2会被打印两遍
/*eg* .先往前查，再往后查，这样比反过来做更能提升效率，因为只要前面出现过了，就说明已经被检查过（打印过了），后面看都不看就会跳过
而如果先往后查，查到有，每次都要回头看看前面有没有出现过以去重，效率比较低（2 2 2 2 2）
*/