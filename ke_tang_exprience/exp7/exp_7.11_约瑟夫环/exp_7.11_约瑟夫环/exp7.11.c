#include<stdio.h>
void main()
{
	int n, m, i=0, count=0, remain;
	int a[1000] = { 0 };
	//注意，如果想让数组中所有元素被赋上一个非零的初值，需要循环遍历赋值，
	// 而不能直接写作={1}，这样只会给第一个数赋值为1，其他都未被初始化
	printf("请输入总人数：");
	scanf_s("%d", &n);
	remain = n;
	printf("请输入到第几位退出：");
	scanf_s("%d", &m);
	printf("退出的顺序为：");
	while (remain > 0)
	{
		if (a[i] == 0)
		{
			count++;
			if (count == m)
			{
				printf("%d ", i + 1);
				a[i] = 1;//这个人退出，但数组位置不变
				remain--;
				count = 0;//循环计数重置为零
			}
		}
		i = (i + 1) % n;//移动到下一个位置，继续以n位“圈”的形式，寻找下一位
		//往前走一步，同时用取余来考虑成环的前提
	}
}
//注意：我们不去删掉退出的数据（因为这样子会改变后面下标的顺序，导致混乱、不好处理）
//我们设置了一个标记的考量，对每一位是否被退出进行考察
//而当count遍历时，就先关注该数是否“在圈中”
// （有在圈中才计数，等效于跳过了被退出的数，但实际上，我们并没有改变数组，下标仍表示原位次）